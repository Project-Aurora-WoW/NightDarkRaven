USE world;

-- Таблица наград магазина
CREATE TABLE IF NOT EXISTS `campaign_shop_items` (
    `item_id` INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    `item_entry` INT UNSIGNED NOT NULL,
    `item_name` VARCHAR(100) NOT NULL,
    `item_description` VARCHAR(255) NOT NULL,
    `campaign_required` SMALLINT UNSIGNED NOT NULL DEFAULT 0, -- 0 = любой
    `quest_required` INT UNSIGNED NOT NULL DEFAULT 0, -- 0 = любой
    `cost_type` ENUM('gold', 'tokens', 'both') NOT NULL DEFAULT 'gold',
    `cost_gold` BIGINT UNSIGNED NOT NULL DEFAULT 0,
    `cost_tokens` INT UNSIGNED NOT NULL DEFAULT 0,
    `max_purchases` INT UNSIGNED NOT NULL DEFAULT 1, -- 0 = без лимита
    `is_active` TINYINT UNSIGNED NOT NULL DEFAULT 1,
    `sort_order` INT UNSIGNED NOT NULL DEFAULT 0,
    UNIQUE KEY `uk_item_entry` (`item_entry`),
    INDEX `idx_campaign_required` (`campaign_required`),
    INDEX `idx_quest_required` (`quest_required`),
    INDEX `idx_sort` (`sort_order`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- Таблица покупок в магазине
CREATE TABLE IF NOT EXISTS `campaign_shop_purchases` (
    `purchase_id` INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    `character_guid` INT UNSIGNED NOT NULL,
    `item_id` INT UNSIGNED NOT NULL,
    `purchased_at` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    INDEX `idx_character` (`character_guid`),
    INDEX `idx_item` (`item_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

